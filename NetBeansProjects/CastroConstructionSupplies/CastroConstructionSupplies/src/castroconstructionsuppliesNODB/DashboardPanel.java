    private void loadDashboardData() {

        lblTotalProducts.setText(String.valueOf(ProductDAO.count()));
        lblTotalInventory.setText(String.format("%,d", ProductDAO.totalStockUnits()));
        lblTotalCustomers.setText(String.valueOf(CustomerDAO.count()));
        lblTotalStaff1.setText(String.valueOf(SaleDAO.queueCount()));
        lblTotalSalesAmount.setText(String.format("₱%,.2f", SaleDAO.totalAmount()));

        int pending = SaleDAO.queueCount();
        lblDashboardSubtitle.setText(pending == 0
                ? "Welcome to Castro's Construction Supplies Management System"
                : "Welcome to Castro's Construction Supplies Management System  —  "
                + pending + " customer order(s) waiting in the queue (see Sales > Order Queue)");

        java.util.List<Product> lowStock = ProductDAO.findLowStock();
        lblLowStock.setText(String.valueOf(lowStock.size()));

        tblRecentSales.setAutoCreateRowSorter(true);
        tblRecentSales.getColumnModel().getColumn(4).setCellRenderer(new CurrencyRenderer());
        javax.swing.table.DefaultTableModel salesModel =
            (javax.swing.table.DefaultTableModel) tblRecentSales.getModel();
        salesModel.setRowCount(0);
        for (Sale sale : SaleDAO.findRecent(10)) {
            salesModel.addRow(new Object[]{
                sale.getId(),
                sale.getDate(),
                sale.getCustomerName(),
                sale.getStaffName(),
                sale.getTotal()
            });
        }

        jTable1.setAutoCreateRowSorter(true);
        jTable1.getColumnModel().getColumn(3).setCellRenderer(new StatusRenderer());
        javax.swing.table.DefaultTableModel stockModel =
            (javax.swing.table.DefaultTableModel) jTable1.getModel();
        stockModel.setRowCount(0);
        for (Product p : lowStock) {
            stockModel.addRow(new Object[]{
                p.getName(), p.getStockQuantity(), p.getReorderLevel(), p.getStockStatus()
            });
        }
    }

