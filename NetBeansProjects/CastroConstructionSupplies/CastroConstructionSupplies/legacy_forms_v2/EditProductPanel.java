    public EditProductPanel() {
        initComponents();
        JTextField.setEditable(false); // Product ID cannot be changed

        // Categories come from the database
        java.util.List<String> categories = CategoryDAO.findAllNames();
        String[] items = new String[categories.size() + 1];
        items[0] = "Select Category";
        for (int i = 0; i < categories.size(); i++) {
            items[i + 1] = categories.get(i);
        }
        cmbCategory.setModel(new javax.swing.DefaultComboBoxModel<>(items));
        btnUpdate.addActionListener(e -> updateProduct());
        btnClear.addActionListener(e -> {
            if (product != null) {
                loadProduct(product, onSaved);
            }
        });
    }

    /** Fills the form with the product being edited. */
    public void loadProduct(Product p, Runnable onSaved) {
        this.product = p;
        this.onSaved = onSaved;
        JTextField.setText(p.getCode());
        jTextField1.setText(p.getName());
        selectOrAdd(cmbCategory, p.getCategory());
        selectOrAdd(cmbUnit, p.getUnit());
        txtPrice.setText(String.valueOf(p.getPrice()));
        txtQuantity.setText(String.valueOf(p.getStockQuantity()));
    }

    private void selectOrAdd(javax.swing.JComboBox<String> combo, String value) {
        for (int i = 0; i < combo.getItemCount(); i++) {
            if (combo.getItemAt(i).equals(value)) {
                combo.setSelectedIndex(i);
                return;
            }
        }
        combo.addItem(value);
        combo.setSelectedItem(value);
    }

    private void updateProduct() {
        if (product == null) {
            return;
        }
        String name = jTextField1.getText().trim();
        if (name.isEmpty()) {
            warn("Please enter the product name.");
            return;
        }
        if (cmbCategory.getSelectedIndex() <= 0 || cmbCategory.getSelectedItem().toString().trim().isEmpty()) {
            warn("Please select a category.");
            return;
        }
        if (cmbUnit.getSelectedIndex() <= 0 || cmbUnit.getSelectedItem().toString().trim().isEmpty()) {
            warn("Please select a unit.");
            return;
        }
        double price;
        int qty;
        try {
            price = Double.parseDouble(txtPrice.getText().trim());
            qty = Integer.parseInt(txtQuantity.getText().trim());
        } catch (NumberFormatException ex) {
            warn("Price must be a number and quantity must be a whole number.");
            return;
        }
        if (price <= 0 || qty < 0) {
            warn("Price must be greater than zero and quantity cannot be negative.");
            return;
        }

        product.setName(name);
        product.setCategory(cmbCategory.getSelectedItem().toString());
        product.setUnit(cmbUnit.getSelectedItem().toString());
        product.setPrice(price);
        product.setStockQuantity(qty);

        if (!ProductDAO.update(product)) {
            return;
        }

        javax.swing.JOptionPane.showMessageDialog(this, "Product updated successfully.",
                "Edit Product", javax.swing.JOptionPane.INFORMATION_MESSAGE);

        if (onSaved != null) {
            onSaved.run();
        }
        java.awt.Window window = javax.swing.SwingUtilities.getWindowAncestor(this);
        if (window != null) {
            window.dispose();
        }
    }

    private void warn(String message) {
        javax.swing.JOptionPane.showMessageDialog(this, message,
                "Validation Error", javax.swing.JOptionPane.WARNING_MESSAGE);
    }

