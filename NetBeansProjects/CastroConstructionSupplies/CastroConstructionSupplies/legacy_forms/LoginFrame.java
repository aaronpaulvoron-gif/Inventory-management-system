    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
String username = txtUsername.getText().trim();
String password = new String(txtPassword.getPassword());
String accountType = cmbAccountType.getSelectedItem().toString();

if (username.isEmpty() || password.isEmpty()) {

    JOptionPane.showMessageDialog(
            this,
            "Please enter your username and password.",
            "Login",
            JOptionPane.WARNING_MESSAGE
    );

    return;
}

// STAFF LOGIN

if (accountType.equals("Staff")) {

    boolean builtInAdmin = username.equals(Session.ADMIN_USERNAME)
            && password.equals(Session.ADMIN_PASSWORD);
    Staff staff = builtInAdmin ? null : StaffDAO.authenticate(username, password);

    if (builtInAdmin || staff != null) {

        String displayName = builtInAdmin ? "Admin" : staff.getFullName();

        Session.currentUserRole = Session.ROLE_STAFF;
        Session.currentUserName = displayName;
        Session.currentStaffId = builtInAdmin ? null : staff.getId();
        Session.currentCustomerId = null;

        JOptionPane.showMessageDialog(
                this,
                "Welcome, " + displayName + "!",
                "Login Successful",
                JOptionPane.INFORMATION_MESSAGE
        );

        MainFrame main = new MainFrame();
        main.setVisible(true);
        this.dispose();

    } else {

        JOptionPane.showMessageDialog(
                this,
                "Invalid username or password, or the account is inactive.",
                "Login Failed",
                JOptionPane.ERROR_MESSAGE
        );
    }
}

// CUSTOMER LOGIN

else if (accountType.equals("Customer")) {

    Customer customer = CustomerDAO.authenticate(username, password);
    boolean found = customer != null;

    if (found) {

        Session.currentUserRole = Session.ROLE_CUSTOMER;
        Session.currentUserName = customer.getFullName();
        Session.currentCustomerId = customer.getId();
        Session.currentStaffId = null;

        JOptionPane.showMessageDialog(
                this,
                "Welcome, " + customer.getFullName() + "!",
                "Login Successful",
                JOptionPane.INFORMATION_MESSAGE
        );

        MainFrame main = new MainFrame();
        main.setVisible(true);
        this.dispose();
    }

    if (!found) {

        JOptionPane.showMessageDialog(
                this,
                "Invalid customer username or password.",
                "Login Failed",
                JOptionPane.ERROR_MESSAGE
        );
    }
}


    }//GEN-LAST:event_btnLoginActionPerformed

