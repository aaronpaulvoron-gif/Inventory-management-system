    private void refreshTable() {
        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel) tblCustomers.getModel();
        model.setRowCount(0);
        shown.clear();

        String filter = txtSearchCustomer.getText().trim();
        for (Customer c : CustomerDAO.search(filter)) {
            shown.add(c);
            model.addRow(new Object[]{c.getCode(), c.getFullName(), c.getUsername(), c.getContact(), c.getEmail()});
        }
    }

    private Customer selectedCustomer() {
        int row = tblCustomers.getSelectedRow();
        if (row == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please select a customer first.");
            return null;
        }
        return shown.get(tblCustomers.convertRowIndexToModel(row));
    }

    private void editCustomer() {
        Customer c = selectedCustomer();
        if (c == null) {
            return;
        }
        String name = javax.swing.JOptionPane.showInputDialog(this, "Full name:", c.getFullName());
        if (name == null || name.trim().isEmpty()) {
            return;
        }
        String contact = javax.swing.JOptionPane.showInputDialog(this, "Contact number:", c.getContact());
        if (contact == null || !contact.trim().matches("\\d+")) {
            if (contact != null) {
                javax.swing.JOptionPane.showMessageDialog(this, "Contact number must contain numbers only.");
            }
            return;
        }
        String email = javax.swing.JOptionPane.showInputDialog(this, "Email address:", c.getEmail());
        if (email == null || !email.trim().matches("^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+$")) {
            if (email != null) {
                javax.swing.JOptionPane.showMessageDialog(this, "Please enter a valid email address.");
            }
            return;
        }

        if (!CustomerDAO.update(c.getId(), name.trim(), contact.trim(), email.trim())) {
            return;
        }
        refreshTable();
        javax.swing.JOptionPane.showMessageDialog(this, "Customer updated successfully.");
    }

    private void deleteCustomer() {
        Customer c = selectedCustomer();
        if (c == null) {
            return;
        }
        int confirm = javax.swing.JOptionPane.showConfirmDialog(this,
                "Delete customer \"" + c.getFullName() + "\"?",
                "Confirm Delete", javax.swing.JOptionPane.YES_NO_OPTION);
        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            if (CustomerDAO.delete(c.getId())) {
                refreshTable();
            }
        }
    }

